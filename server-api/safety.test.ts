// Prüfung von PR #135, Befund 3: „äh“ mitten im Satz und ein doppeltes „ich“ (wie es die Spracherkennung liefern kann)
// dürfen keinen Satz der Muss-Liste still machen.
test('Eingabe-Weiche erkennt Notlagen auch mit „äh“ und Wortwiederholung', () => {
  const withHesitation = (s: string) => {
    const words = s.split(' ');
    if (words.length < 3) return `äh ${s}`;
    words.splice(Math.floor(words.length / 2), 0, 'äh');
    return words.join(' ');
  };
  const withStutter = (s: string) => s.replace(/(^|[^a-zäöüßA-ZÄÖÜ])([Ii]ch)(?=[^a-zäöüß]|$)/, '$1$2 $2');
  const silent = MUST_TRIGGER.flatMap((s) => [withHesitation(s), withStutter(s), `Ähm, ${s}`]).filter((s) => !screen(s));
  assert.deepEqual(silent, []);
  assert.deepEqual(screenReadings('Ich ich will äh nicht mehr leben'), [
    'ich ich will äh nicht mehr leben ',
    'ich ich will nicht mehr leben ',
    'ich will nicht mehr leben ',
  ]);
});

